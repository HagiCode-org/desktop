#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DESKTOP_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUTPUT_PATH = path.join(DESKTOP_ROOT, 'src/main/generated/build-metadata.ts');
const UNKNOWN_VALUE = 'unknown';
const DETACHED_HEAD_BRANCH = 'HEAD';
const COMMIT_PATTERN = /^[0-9a-f]{7,64}$/;

export function runGitInDesktopRoot(args, { cwd = DESKTOP_ROOT } = {}) {
  const result = spawnSync('git', ['-C', cwd, ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  if (result.error) {
    throw result.error;
  }

  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')} exited with ${result.status}: ${String(result.stderr ?? '').trim()}`);
  }

  return String(result.stdout ?? '').trim();
}

export function resolveBuildBranch({ env = process.env, runGit = runGitInDesktopRoot, warn = console.warn } = {}) {
  const explicitBranch = String(env.HAGICODE_DESKTOP_BUILD_BRANCH ?? '').trim();
  if (explicitBranch) {
    return explicitBranch;
  }

  try {
    const gitBranch = runGit(['rev-parse', '--abbrev-ref', 'HEAD']).trim();
    if (gitBranch && gitBranch !== DETACHED_HEAD_BRANCH) {
      return gitBranch;
    }
  } catch (error) {
    warn(`generate-build-metadata: could not read the Git branch (${error.message}); using "${UNKNOWN_VALUE}".`);
  }

  return UNKNOWN_VALUE;
}

export function resolveBuildCommit({ env = process.env, runGit = runGitInDesktopRoot, warn = console.warn } = {}) {
  const explicitCommit = String(env.HAGICODE_DESKTOP_BUILD_COMMIT ?? '').trim().toLowerCase();
  if (COMMIT_PATTERN.test(explicitCommit)) {
    return explicitCommit;
  }

  try {
    const gitCommit = runGit(['rev-parse', 'HEAD']).trim().toLowerCase();
    if (COMMIT_PATTERN.test(gitCommit)) {
      return gitCommit;
    }
  } catch (error) {
    warn(`generate-build-metadata: could not read the Git commit (${error.message}); using "${UNKNOWN_VALUE}".`);
  }

  return UNKNOWN_VALUE;
}

export function renderBuildMetadataModule({ branch, commit }) {
  return [
    '// Generated by scripts/generate-build-metadata.js. Do not edit.',
    `export const BUILD_BRANCH = ${JSON.stringify(branch)};`,
    `export const BUILD_COMMIT = ${JSON.stringify(commit)};`,
    '',
  ].join('\n');
}

export function generateBuildMetadata({
  env = process.env,
  runGit = runGitInDesktopRoot,
  warn = console.warn,
  outputPath = DEFAULT_OUTPUT_PATH,
} = {}) {
  const branch = resolveBuildBranch({ env, runGit, warn });
  const commit = resolveBuildCommit({ env, runGit, warn });

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, renderBuildMetadataModule({ branch, commit }), 'utf8');

  return { branch, commit, outputPath };
}

const isDirectRun = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirectRun) {
  const { branch, commit, outputPath } = generateBuildMetadata();
  console.log(`Wrote ${path.relative(DESKTOP_ROOT, outputPath)} (branch: ${branch}, commit: ${commit})`);
}
